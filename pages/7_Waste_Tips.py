"""
pages/7_Waste_Tips.py
-----------------------
Waste-reduction tips & suggestions.

The Dashboard shows WHAT was wasted; this page tells you WHAT TO DO
about it. Suggestions are generated by simple, explainable rules in
engine.get_waste_reduction_suggestions() from your live stock, usage
and waste data — no AI or internet needed.
"""

import streamlit as st
from engine import get_waste_reduction_suggestions, GENERAL_TIPS
from style import inject_custom_css, show_footer

st.set_page_config(page_title="Waste Tips", page_icon="💡", layout="wide")
inject_custom_css()
st.title("💡 Waste Reduction Tips")
st.markdown("Smart suggestions based on your current stock, usage and waste history.")
st.divider()

lookback = st.radio("Waste history to analyse", [7, 14, 30, 60, 90], index=2,
                    format_func=lambda d: f"Last {d} days", horizontal=True)

suggestions = get_waste_reduction_suggestions(lookback_days=lookback)

PRIORITY_STYLE = {
    "High": ("🔴", st.error),
    "Medium": ("🟠", st.warning),
    "Low": ("🟢", st.success),
}

high = sum(1 for s in suggestions if s["priority"] == "High")
medium = sum(1 for s in suggestions if s["priority"] == "Medium")
saving = sum(s["potential_saving"] for s in suggestions)

c1, c2, c3 = st.columns(3)
c1.metric("High-priority tips", high)
c2.metric("Medium-priority tips", medium)
c3.metric("Potential saving", f"₹{saving:,.2f}",
          help="Estimated value of stock at risk or waste that these tips could prevent. An estimate, not a guarantee.")

st.divider()

if not suggestions:
    st.success("✅ No waste-reduction issues detected right now. Keep logging usage and waste so the tips stay accurate.")
else:
    chosen = st.multiselect("Show priorities", ["High", "Medium", "Low"],
                            default=["High", "Medium", "Low"])
    shown = [s for s in suggestions if s["priority"] in chosen]
    if not shown:
        st.caption("No tips match the selected priorities.")
    for idx, s in enumerate(shown):
        icon, _ = PRIORITY_STYLE[s["priority"]]
        with st.container(border=True):
            left, right = st.columns([5, 1.4])
            left.markdown(f"**{icon} {s['title']}**")
            left.write(s["message"])
            meta = f"Rule: {s['rule']} · Priority: {s['priority']}"
            if s["potential_saving"] > 0:
                meta += f" · Potential saving ≈ ₹{s['potential_saving']:,.2f}"
            left.caption(meta)
            if s["action_page"]:
                label = {
                    "pages/5_Waste.py": "Log Waste →",
                    "pages/4_Usage.py": "Log Usage →",
                    "pages/3_Purchases.py": "Purchases →",
                    "pages/1_Categories.py": "Categories →",
                    "pages/6_Dashboard.py": "Dashboard →",
                }.get(s["action_page"], "Open →")
                if right.button(label, key=f"tip_{idx}"):
                    if s["ingredient_id"] is not None:
                        st.session_state["prefill_ingredient_id"] = s["ingredient_id"]
                    st.switch_page(s["action_page"])

st.divider()
with st.expander("📚 General best practices for reducing food waste"):
    for title, text in GENERAL_TIPS:
        st.markdown(f"**{title}** — {text}")

with st.expander("ℹ️ How are these tips generated?"):
    st.markdown("""
Each tip comes from a transparent rule applied to your own data:

1. **Expired / expiring stock** — batches past or near their expiry date.
2. **Over-stocking** — stock that will likely expire before it is used, based on average daily usage and FEFO order.
3. **Top wasted ingredient** — one ingredient causing ≥25% of waste cost.
4. **Dominant waste reason** — e.g. most waste is spoilage → check storage.
5. **Category hotspot** — one category causing ≥40% of waste cost.
6. **Waste trend** — waste this week vs last week.
7. **Waste vs spend** — waste above 5% of purchase cost.
    """)

show_footer()
